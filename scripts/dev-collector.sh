#!/bin/sh
# Aegis local development helper (POSIX sh; works on macOS and Linux).
#
# Default (no flags): starts public/downloads/aegis_collector.py on
# 127.0.0.1:8931 with freshly generated demo credentials, writes a frontend
# .env.local pointing at it, and seeds 5 demo device reports with curl.
#
# Usage:
#   scripts/dev-collector.sh           start collector + seed demo data
#   scripts/dev-collector.sh --seed    seed demo data into a running collector
#   scripts/dev-collector.sh --stop    stop the background collector
#   scripts/dev-collector.sh --help    show this help
set -eu

usage() {
    cat <<'USAGE'
Usage: scripts/dev-collector.sh [--seed | --stop | --help]

  (no args)  Start the Aegis collector on 127.0.0.1:8931 with demo
             credentials, write .env.local for the frontend, and seed
             5 demo device reports.
  --seed     Seed 5 demo device reports into an already running collector
             (uses the credentials stored in .dev/collector.env).
  --stop     Stop the background collector started by this script.
  --help     Show this help.

State lives in .dev/ (gitignored): collector DB, log, PID file, and the
generated demo credentials.
USAGE
}

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
COLLECTOR_PY="$ROOT/public/downloads/aegis_collector.py"
DEV_DIR="$ROOT/.dev"
CRED_FILE="$DEV_DIR/collector.env"
PID_FILE="$DEV_DIR/collector.pid"
LOG_FILE="$DEV_DIR/collector.log"
DB_FILE="$DEV_DIR/aegis-collector.db"
ENV_LOCAL="$ROOT/.env.local"
HOST=127.0.0.1
PORT=${AEGIS_DEV_COLLECTOR_PORT:-8931}
BASE_URL="http://$HOST:$PORT"
TMP_DIR=""

cleanup() {
    if [ -n "$TMP_DIR" ] && [ -d "$TMP_DIR" ]; then
        rm -rf "$TMP_DIR"
    fi
}
trap cleanup EXIT INT TERM

die() {
    printf 'error: %s\n' "$1" >&2
    exit 1
}

need() {
    command -v "$1" >/dev/null 2>&1 || die "'$1' is required but was not found in PATH"
}

gen_secret() {
    # 64-char lowercase hex (256 bits)
    python3 -c 'import secrets; print(secrets.token_hex(32))'
}

collector_pid() {
    if [ -f "$PID_FILE" ]; then
        pid=$(cat "$PID_FILE" 2>/dev/null || true)
        if [ -n "${pid:-}" ] && kill -0 "$pid" 2>/dev/null; then
            printf '%s' "$pid"
            return 0
        fi
    fi
    return 1
}

wait_healthy() {
    tries=0
    while [ "$tries" -lt 30 ]; do
        if curl -fsS -o /dev/null "$BASE_URL/health" 2>/dev/null; then
            return 0
        fi
        if ! collector_pid >/dev/null; then
            printf 'collector exited during startup; last log lines:\n' >&2
            tail -n 20 "$LOG_FILE" >&2 || true
            die "collector failed to start"
        fi
        tries=$((tries + 1))
        sleep 1
    done
    die "collector did not become healthy at $BASE_URL/health within 30s"
}

load_or_create_credentials() {
    need python3
    mkdir -p "$DEV_DIR"
    if [ -f "$CRED_FILE" ]; then
        # shellcheck disable=SC1090
        . "$CRED_FILE"
        DEV_TOKEN=$AEGIS_COLLECTOR_TOKEN
        DEV_SIGNING_SECRET=$AEGIS_REPORT_SIGNING_SECRET
    else
        DEV_TOKEN=$(gen_secret)
        DEV_SIGNING_SECRET=$(gen_secret)
        (
            umask 077
            cat > "$CRED_FILE" <<EOF
# Demo-only credentials generated by scripts/dev-collector.sh. Never commit.
AEGIS_COLLECTOR_TOKEN=$DEV_TOKEN
AEGIS_REPORT_SIGNING_SECRET=$DEV_SIGNING_SECRET
EOF
        )
        printf 'generated demo credentials in %s\n' "$CRED_FILE"
    fi
}

write_env_local() {
    cat > "$ENV_LOCAL" <<EOF
AEGIS_COLLECTOR_URL=http://127.0.0.1:$PORT
AEGIS_COLLECTOR_ALLOWED_HOST=$HOST
AEGIS_COLLECTOR_TOKEN=$DEV_TOKEN
EOF
    printf 'wrote %s\n' "$ENV_LOCAL"
}

start_collector() {
    [ -f "$COLLECTOR_PY" ] || die "missing $COLLECTOR_PY"
    if pid=$(collector_pid); then
        printf 'collector already running (pid %s) at %s\n' "$pid" "$BASE_URL"
        return 0
    fi
    mkdir -p "$DEV_DIR"
    AEGIS_COLLECTOR_TOKEN=$DEV_TOKEN \
    AEGIS_REPORT_SIGNING_SECRET=$DEV_SIGNING_SECRET \
    AEGIS_REQUESTS_PER_MINUTE=600 \
    AEGIS_REQUIRED_AGENT_VERSION=0.30.0 \
    AEGIS_REQUIRED_POLICY_VERSION=4.8.0 \
    nohup python3 "$COLLECTOR_PY" --listen "$HOST" --port "$PORT" --db "$DB_FILE" \
        >> "$LOG_FILE" 2>&1 &
    printf '%s\n' "$!" > "$PID_FILE"
    printf 'started collector (pid %s) at %s, log: %s\n' "$(cat "$PID_FILE")" "$BASE_URL" "$LOG_FILE"
    wait_healthy
    printf 'collector health check passed\n'
}

post_report_body() {
    # $1: path to a file holding the exact JSON report body.
    body_file=$1
    ts=$(date +%s)
    { printf '%s.' "$ts"; cat "$body_file"; } > "$TMP_DIR/signed.bin"
    sig=$(openssl dgst -sha256 -hmac "$DEV_SIGNING_SECRET" "$TMP_DIR/signed.bin" | awk '{print $NF}')
    status=$(curl -s -o "$TMP_DIR/response.json" -w '%{http_code}' \
        -X POST "$BASE_URL/v1/reports" \
        -H "Authorization: Bearer $DEV_TOKEN" \
        -H "Content-Type: application/json" \
        -H "X-Aegis-Timestamp: $ts" \
        -H "X-Aegis-Signature: sha256=$sig" \
        --data-binary "@$body_file")
    case "$status" in
        200|202)
            device=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["device_id"])' "$body_file")
            printf 'seeded report for %s (HTTP %s)\n' "$device" "$status"
            ;;
        *)
            cat "$TMP_DIR/response.json" >&2 || true
            die "collector rejected a demo report (HTTP $status)"
            ;;
    esac
}

