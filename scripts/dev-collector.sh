stop_collector() {
    if pid=$(collector_pid); then
        kill "$pid" 2>/dev/null || true
        tries=0
        while [ "$tries" -lt 10 ] && kill -0 "$pid" 2>/dev/null; do
            sleep 1
            tries=$((tries + 1))
        done
        if kill -0 "$pid" 2>/dev/null; then
            kill -9 "$pid" 2>/dev/null || true
        fi
        rm -f "$PID_FILE"
        printf 'stopped collector (pid %s)\n' "$pid"
    else
        rm -f "$PID_FILE"
        printf 'collector is not running\n'
    fi
}

print_instructions() {
    cat <<EOF

Next steps:
  1. Install frontend dependencies (first time only):
       npm install
  2. Start the console dev server:
       npm run dev
  3. Open http://localhost:3000 -- the console reads .env.local and
     proxies fleet data from the collector at $BASE_URL

Useful commands:
  Tail collector log:        tail -f .dev/collector.log
  Seed 5 more demo reports:  scripts/dev-collector.sh --seed
  Seed a larger demo fleet:  python3 scripts/seed-demo-reports.py --collector-url $BASE_URL --token <token in .dev/collector.env>
  Stop the collector:        scripts/dev-collector.sh --stop
EOF
}

mode=start
case "${1:-}" in
    --stop) mode=stop ;;
    --seed) mode=seed ;;
    --help|-h) usage; exit 0 ;;
    "") ;;
    *) usage >&2; die "unknown argument: $1" ;;
esac

case "$mode" in
    start)
        need python3
        need curl
        need openssl
        load_or_create_credentials
        write_env_local
        start_collector
        seed_demo_reports
        print_instructions
        ;;
    seed)
        [ -f "$CRED_FILE" ] || die "no demo credentials found at $CRED_FILE; run 'scripts/dev-collector.sh' once to start the collector first"
        load_or_create_credentials
        curl -fsS -o /dev/null "$BASE_URL/health" || die "collector is not reachable at $BASE_URL/health; run 'scripts/dev-collector.sh' to start it"
        seed_demo_reports
        ;;
    stop)
        stop_collector
        ;;
esac
